#!/usr/bin/env python3
"""Generate native macOS string tables from the macOS app translation catalog."""
import itertools,json,pathlib,plistlib,re,sys
check="--check" in sys.argv
root=pathlib.Path(__file__).resolve().parents[1]
values=json.loads((root/'Sources/TwisterCore/Resources/Turkish.json').read_text())
values.update({key.upper():value.replace('i','İ').replace('ı','I').upper() for key,value in list(values.items()) if not re.search(r'\{\d\}',key)})
# SwiftUI interpolates strings as %@ and integer counts as %lld.
for key,value in list(values.items()):
 count=len(re.findall(r'\{\d\}',key))
 if count:
  for formats in itertools.product(['%@','%lld'],repeat=count):
   source=key;target=value
   for index,fmt in enumerate(formats):
    source=source.replace('{'+str(index)+'}',fmt)
    target=target.replace('{'+str(index)+'}',fmt)
   values[source]=target
for language in ['en','tr']:
 directory=root/'Resources/Localizations'/f'{language}.lproj'
 if not check:directory.mkdir(parents=True,exist_ok=True)
 lines=['/* Generated by scripts/generate-localizations.py; edit Turkish.json. */']
 for key,value in sorted(values.items()):
  if re.search(r'\{\d\}',key):continue
  lines.append(json.dumps(key,ensure_ascii=False)+' = '+json.dumps(key if language=='en' else value,ensure_ascii=False)+';')
 path=directory/'Localizable.strings';expected='\n'.join(lines)+'\n'
 if check:
  if not path.exists() or path.read_text()!=expected:raise SystemExit(f'Stale generated localization table: {path.relative_to(root)}')
 else:path.write_text(expected)
 # Finder shows the Services entries of Info.plist through this table.
 lines=['/* Generated by scripts/generate-localizations.py; edit Turkish.json. */']
 for service in plistlib.loads((root/'Resources/Info.plist').read_bytes()).get('NSServices',[]):
  title=service['NSMenuItem']['default']
  if title not in values:raise SystemExit(f'Services entry has no Turkish title: {title}')
  lines.append(json.dumps(title,ensure_ascii=False)+' = '+json.dumps(title if language=='en' else values[title],ensure_ascii=False)+';')
 path=directory/'ServicesMenu.strings';expected='\n'.join(lines)+'\n'
 if check:
  if not path.exists() or path.read_text()!=expected:raise SystemExit(f'Stale generated localization table: {path.relative_to(root)}')
 else:path.write_text(expected)
print(f'Generated English/Turkish native tables: {len(values)} keys')
